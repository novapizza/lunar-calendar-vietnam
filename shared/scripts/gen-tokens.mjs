// Generates the web theme from shared/design/tokens.json and copies the logo.
//   node shared/scripts/gen-tokens.mjs           write the files
//   node shared/scripts/gen-tokens.mjs --check   exit 1 if a file is out of date
//
// Outputs:
//   apps/web/src/theme.generated.css   base light/dark colours + one palette per mệnh element
//   apps/web/public/icon.svg           copy of shared/design/icon.svg (favicon, PWA icon source)
// The iOS and Android apps read tokens.json the same way (their generators come with the apps).

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const tokens = JSON.parse(readFileSync(join(root, 'shared/design/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');

const vars = (values, indent) =>
  Object.entries(values)
    .flatMap(([name, value]) => [
      ...(tokens.descriptions[name] ? [`${indent}/* ${tokens.descriptions[name]} */`] : []),
      `${indent}--${name}: ${value};`,
    ])
    .join('\n');

// Palette rules: light rules beat :root by order; dark rules carry one more
// selector part so they beat both the light rule and the base dark colours.
// The attribute also works on any element, so a swatch can preview a palette.
const palette = (name, { light, dark }) => {
  const a = `[data-palette="${name}"]`;
  return `${a} {
${vars(light, '  ')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"])${a},
  :root:not([data-theme="light"]) ${a} {
${vars(dark, '    ')}
  }
}
:root[data-theme="dark"]${a},
:root[data-theme="dark"] ${a} {
${vars(dark, '  ')}
}`;
};

const css = `/* GENERATED by shared/scripts/gen-tokens.mjs from shared/design/tokens.json. Do not edit: run npm run gen. */

:root {
${vars(tokens.base.light, '  ')}

  color-scheme: light;
}

/* Dark colours: follow the system unless the user picked a theme
   (html[data-theme="light" | "dark"], set in index.html and useTheme). */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(tokens.base.dark, '    ')}

    color-scheme: dark;
  }
}

:root[data-theme="dark"] {
${vars(tokens.base.dark, '  ')}

  color-scheme: dark;
}

/* Palettes by mệnh: html[data-palette] set by useAccent; no attribute = default red. */
${Object.entries(tokens.palettes).map(([name, p]) => palette(name, p)).join('\n\n')}
`;

const outputs = [
  ['apps/web/src/theme.generated.css', css],
  ['apps/web/public/icon.svg', readFileSync(join(root, 'shared/design/icon.svg'), 'utf8')],
];

let stale = 0;
for (const [rel, content] of outputs) {
  const file = join(root, rel);
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (current === content) continue;
  if (check) { console.error(`out of date: ${rel} (run npm run gen)`); stale++; }
  else { writeFileSync(file, content); console.log(`wrote ${rel}`); }
}
if (stale) process.exit(1);
if (check) console.log('tokens: up to date');
